    response = await client.post(
        "/api/demo/analyze",
        json={
            "analysis_mode": "simulated_ai",
            "user_message": "Summarize this demonstration record.",
            "rag_content": "Demo patient A has hypertension.",
        },
    )
    body = await response.json()

    assert response.status == 200
    assert body["ai_output"].startswith("Clinical summary based on the supplied demonstration record")
    assert "Simulated clinical assistant output" not in body["ai_output"]


